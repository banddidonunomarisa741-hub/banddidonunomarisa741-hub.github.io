export const AXIS_LON = 116.3911;          // 元明清中轴线经度（永定门—钟楼）
export const JIN_AXIS_LON = 116.3440;      // 金中都中轴线经度（丰宜门—通玄门）
const M_LON = 85390, M_LAT = 111000;       // 北纬 39.9° 处每度经/纬的米数

// 总图：1 格 = 25 米
export const MAP = {
  unit: 25, lon0: AXIS_LON, lat0: 39.9072,
  bounds: { x0: -330, x1: 255, z0: -400, z1: 256 },
};
export function mapXZ(lon, lat) {
  return [((lon - MAP.lon0) * M_LON) / MAP.unit, (-(lat - MAP.lat0) * M_LAT) / MAP.unit];
}
export function mapLL(x, z) {
  return [MAP.lon0 + (x * MAP.unit) / M_LON, MAP.lat0 - (z * MAP.unit) / M_LAT];
}

