export function nearestPlace(lon, lat) {
  let best = null, bd = Infinity;
  for (const [n, a, b] of PLACES) {
    const d = Math.hypot((a - lon) * M_LON, (b - lat) * M_LAT);
    if (d < bd) { bd = d; best = n; }
  }
  return { name: best, dist: bd };
}

