function interp(pairs, v, from = 0, to = 1) {
  const p = pairs.slice().sort((a, b) => a[from] - b[from]);
  let i = 0;
  if (v <= p[0][from]) i = 0;
  else if (v >= p[p.length - 1][from]) i = p.length - 2;
  else while (i < p.length - 2 && v > p[i + 1][from]) i++;
  const a = p[i], b = p[i + 1];
  const t = (v - a[from]) / (b[from] - a[from]);
  return a[to] + (b[to] - a[to]) * t;
}
export function eraToLL(era, x, z) {
  const g = ERA_GEO[era];
  if (!g) return mapLL(x, z);
  return [interp(g.x, x), interp(g.z, z)];
}
export function llToEra(era, lon, lat) {
  const g = ERA_GEO[era];
  if (!g) return mapXZ(lon, lat);
  return [interp(g.x, lon, 1, 0), interp(g.z, lat, 1, 0)];
}

export function fmtLL(lon, lat) {
  return `北纬 ${lat.toFixed(4)}° · 东经 ${lon.toFixed(4)}°`;
}

