export function routesFor(era, nodes) {
  if (era === 'qing' || era === 'modern') {
    return [
      { id: 'oneday', name: '一日游 · 精华线', sub: '沿中轴线由南向北，只停最重要的建筑', parts: [{ name: '全天', stops: ONE_DAY[era] }] },
      {
        id: 'halfday', name: '两个半天 · 详细线', sub: '上午南段、下午北段，加上两侧的坛庙与宫院',
        parts: [
          { name: '上午 · 南段（燕墩—天安门）', stops: HALF_AM[era] },
          { name: '下午 · 北段（端门—钟楼）', stops: HALF_PM[era] },
        ],
      },
    ];
  }
  return [{ id: 'axis', name: '沿中轴线', sub: '由南向北依次经过本时期的轴线建筑', parts: [{ name: '全程', stops: nodes.map((n) => n.id) }] }];
}

export function stopText(id, era) {
  const s = STOPS[id];
  if (!s) return null;
  const o = s[era] || {};
  return { hist: o.hist ?? s.hist, use: o.use ?? s.use, look: o.look ?? s.look, shot: s.shot, view: s.view };
}
